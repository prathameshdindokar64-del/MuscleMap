import { useState } from 'react'
import { acupressurePointsForResults } from '../../constants/acupressure'
import { FALLBACK_DISCLAIMER } from '../../constants/api'
import type { AcupressurePoint, AnalyzePainResponse } from '../../types'
import { exportPdf } from '../../api/painApi'
import { useAuth } from '../../context/AuthContext'
import { ExerciseCard } from './ExerciseCard'
import { RiskBadge } from './RiskBadge'

function AcupressureCard({ point, isDarkTheme }: { point: AcupressurePoint; isDarkTheme: boolean }) {
  const [open, setOpen] = useState(false)
  const cardStyle = isDarkTheme
    ? { background: 'rgba(245, 158, 11, 0.05)', border: '1px solid rgba(245, 158, 11, 0.2)', backdropFilter: 'blur(12px)' as const }
    : { background: 'rgba(255, 251, 235, 0.7)', border: '1px solid rgba(245, 158, 11, 0.3)', backdropFilter: 'blur(12px)' as const }

  return (
    <article className="rounded-xl p-4" style={cardStyle}>
      <p className="flex items-center gap-2 text-sm font-bold" style={{ color: '#f59e0b' }}>
        <span className="inline-block h-2 w-2 animate-pulse rounded-full bg-amber-500" />
        {point.name}
      </p>
      <p className="mt-2 text-xs" style={{ color: 'var(--text-secondary)' }}>
        {point.description}
      </p>
      <button type="button" className="mt-2 text-xs font-semibold text-amber-600" onClick={() => setOpen((o) => !o)}>
        Technique {open ? '▲' : '▼'}
      </button>
      {open && (
        <p className="mt-2 text-xs leading-relaxed" style={{ color: 'var(--text-muted)' }}>
          {point.technique}
        </p>
      )}
    </article>
  )
}

/** Shows API analysis output after form submission. */
export function Results({
  result,
  regionId,
  isDarkTheme,
  onReset,
}: {
  result: AnalyzePainResponse
  regionId: string
  isDarkTheme: boolean
  onReset: () => void
}) {
  const { user } = useAuth()
  const [exporting, setExporting] = useState(false)
  const [exportError, setExportError] = useState<string | null>(null)
  const acupressure = acupressurePointsForResults(regionId, result.acupressurePoints)

  async function handleExport() {
    setExporting(true)
    setExportError(null)
    try {
      await exportPdf(result, { name: user?.name || 'Anonymous' })
    } catch (err: any) {
      setExportError(err.message || 'Failed to generate PDF')
    } finally {
      setExporting(false)
    }
  }

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap gap-2">
        {result.muscles.map((muscleName) => (
          <span
            key={muscleName}
            className="rounded-full px-3 py-1 text-xs font-medium"
            style={{ background: 'var(--accent-glow)', color: 'var(--text-accent)', border: '1px solid var(--glass-border-accent)' }}
          >
            {muscleName}
          </span>
        ))}
      </div>

      {/* AI Insight */}
      {result.aiInsight && (
        <div
          className="rounded-xl p-4 space-y-1"
          style={{
            background: isDarkTheme ? 'rgba(13,148,136,0.08)' : 'rgba(13,148,136,0.06)',
            border: '1px solid rgba(13,148,136,0.25)',
            backdropFilter: 'blur(12px)',
          }}
        >
          <p className="text-xs font-bold" style={{ color: 'var(--text-accent)' }}>🤖 AI Insight</p>
          <p className="text-sm leading-relaxed" style={{ color: 'var(--text-secondary)' }}>
            {result.aiInsight}
          </p>
          {result.generatedBy && (
            <p className="text-xs" style={{ color: 'var(--text-muted)', opacity: 0.7 }}>
              Generated by: {result.generatedBy}
            </p>
          )}
        </div>
      )}

      {/* Exercises */}
      <div className="space-y-3">
        {result.exercises.map((exercise) => (
          <ExerciseCard key={exercise.title} exercise={exercise} />
        ))}
      </div>

      {/* Recovery Tips */}
      {result.recoveryTips && result.recoveryTips.length > 0 && (
        <div
          className="rounded-xl p-4 space-y-2"
          style={{
            background: isDarkTheme ? 'rgba(99,102,241,0.08)' : 'rgba(99,102,241,0.06)',
            border: '1px solid rgba(99,102,241,0.2)',
          }}
        >
          <p className="text-xs font-bold" style={{ color: '#818cf8' }}>💡 Recovery Tips</p>
          <ul className="space-y-1">
            {result.recoveryTips.map((tip, i) => (
              <li key={i} className="flex items-start gap-2 text-xs" style={{ color: 'var(--text-secondary)' }}>
                <span style={{ color: '#818cf8', flexShrink: 0 }}>▸</span>
                {tip}
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* Acupressure */}
      {acupressure.length > 0 && (
        <div className="space-y-3">
          <h4 className="text-lg font-semibold" style={{ color: 'var(--text-primary)' }}>
            🫧 Acupressure Points
          </h4>
          <p className="text-xs" style={{ color: 'var(--text-muted)' }}>
            Apply gentle pressure to these points for additional relief
          </p>
          <div className="space-y-3">
            {acupressure.map((point) => (
              <AcupressureCard key={point.name} point={point} isDarkTheme={isDarkTheme} />
            ))}
          </div>
        </div>
      )}

      <RiskBadge risk={result.riskLevel} />

      {result.warningText && (
        <div className="rounded-md p-3 text-sm font-semibold" style={{ background: 'rgba(239,68,68,0.15)', color: 'var(--risk-severe)' }}>
          {result.warningText}
        </div>
      )}
      <div
        className="rounded-md border-l-4 p-3 italic"
        style={{
          borderColor: 'var(--disclaimer-border)',
          background: 'var(--disclaimer-bg)',
          color: 'var(--disclaimer-text)',
        }}
      >
        {result.disclaimerText || FALLBACK_DISCLAIMER}
      </div>

      {/* PDF Export */}
      {exportError && (
        <div className="rounded-md p-3 text-sm" style={{ background: 'rgba(239,68,68,0.12)', color: '#f87171' }}>
          {exportError}
        </div>
      )}
      <button
        type="button"
        onClick={handleExport}
        disabled={exporting}
        className="glass-accent w-full rounded-md p-3 font-semibold"
        style={{ opacity: exporting ? 0.7 : 1, cursor: exporting ? 'not-allowed' : 'pointer' }}
      >
        {exporting ? '⏳ Generating PDF...' : '📄 Export Full Report as PDF'}
      </button>

      <button
        type="button"
        onClick={onReset}
        className="glass w-full rounded-md border p-2 font-medium"
        style={{ borderColor: 'var(--glass-border-accent)', color: 'var(--text-accent)' }}
      >
        Start New Assessment
      </button>
    </div>
  )
}
